export type ReciterId = (typeof RECITERS)[number]["id"];

export const DEFAULT_RECITER: ReciterId = "alafasy";

export const isReciterId = (value: unknown): value is ReciterId =>
  RECITERS.some((r) => r.id === value);

export const getReciter = (id: ReciterId) =>
  RECITERS.find((r) => r.id === id) ?? RECITERS[0];

const pad = (n: number) => String(n).padStart(3, "0");

export const ayahAudioUrl = (id: ReciterId, surah: number, ayah: number) =>
  `https://everyayah.com/data/${getReciter(id).folder}/${pad(surah)}${pad(ayah)}.mp3`;
